function addTimbreToSectionHeaders(lyrics: string, vocalTimbre: string): string {
  const timbreLabel = vocalTimbre.replace(/-/g, ' ');
  return lyrics.split('\n').map(line => {
    if (!line.startsWith('[') || !line.endsWith(']') || line.includes(timbreLabel)) return line;
    return `${line.slice(0, -1)} | ${timbreLabel}]`;
  }).join('\n');
}

