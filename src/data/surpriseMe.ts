export function pickRandomSurpriseRecipe(): SurpriseRecipe {
  const idx = Math.floor(Math.random() * SURPRISE_RECIPES.length);
  return SURPRISE_RECIPES[idx];
}

export function applySurpriseRecipeToState(current: any, recipe: SurpriseRecipe): any {
  const defaultStudioUnwanted = [
    'crowd', 'applause', 'audience', 'cheering', 'screaming', 'live-performance', 'stadium-echo', 'whistle'
  ];
  const recipeNegatives = (recipe.negativeTags || []).map(t => t.replace(/^no-/, ''));
  return {
    ...current,
    genres: [...recipe.genres],
    subgenres: [...recipe.subgenres],
    instruments: [...recipe.instruments],
    customInstruments: [],
    vocalTypes: [...recipe.vocalTypes],
    vocalEffects: [...recipe.vocalEffects],
    moods: [...recipe.moods],
    production: Array.from(new Set([...recipe.production, 'hifi-studio', 'clean-mix'])),
    negativeTags: Array.from(new Set([...defaultStudioUnwanted, ...recipeNegatives])),
    musicalKeys: [...recipe.musicalKeys],
    chordVoicings: [...recipe.chordVoicings],
    bpm: recipe.bpm,
    timeFeel: recipe.timeFeel,
    blend: recipe.blend,
    artistArchetypes: [...recipe.artistArchetypes],
    artistBlend: recipe.artistBlend,
    lyrics: addTimbreToSectionHeaders(recipe.lyrics, recipe.vocalTimbre),
    duetMode: false,
  };
}
